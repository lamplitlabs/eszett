export const sceneIcon = (key: string): LucideIcon => SCENE_ICONS[key] ?? Drama;

/** The icon of a scene, as an element (no component is created while rendering). */
export function SceneIcon({ sceneKey, size, color, strokeWidth = 1.9 }: { sceneKey: string; size: number; color: string; strokeWidth?: number }) {
  return createElement(sceneIcon(sceneKey), { size, color, strokeWidth });
}
